export type CropGroup =
  "trained" | "exotic" | "seasonal" | "export" | "flower" | "mushroom" | "greens";
export interface Crop {
  key: string;
  en: string;
  hi: string;
  emoji: string;
  rate: number;
  temp: string;
  agmark: string[];
  group: CropGroup;
  /** Hours it stays sellable at room temperature after harvest (grade A, ripe). */
  shelfH: number;
  /** Hours it stays sellable when kept in the right cold chain from harvest. */
  shelfColdH: number;
  /** Climacteric: keeps ripening after harvest, so unripe lots can go to a ripening chamber. */
  ripens?: boolean;
  trained?: boolean;
}

